const body = document.body;

const totalQuestions = cricketQuizQuestions.length;
let totalMarks = 0;

const generateRandomNumbers = (totalNumbers) => {
    let randomNumbers = [-1, -1, -1, -1 , -1];

    for(let i = 0; i < totalNumbers; i++)
    {
      let number = Math.floor(Math.random() * totalQuestions);
      if(!randomNumbers.includes(number))
        randomNumbers[i] = number
      else
        i--;
    }
    return randomNumbers;
}

const randomNumbers = generateRandomNumbers(5);

const generateForm = () => {
  const createForm = document.createElement("form")
  

  body.appendChild(createForm)
  for(let i = 0; i < randomNumbers.length; i++)
  {

    let getQuestion = cricketQuizQuestions[randomNumbers[i]]
  
    const createParagraph = document.createElement("p")
    const optionsContainer = document.createElement("div");

    createParagraph.textContent =  `Question: ${i+1}: ${getQuestion.question}`;

    getQuestion.options.forEach(option => {
      optionsContainer.innerHTML += `
        <label>
          <input type="radio" name="${getQuestion.id}" value="${option}"> ${option}
        </label><br>
      `;
  });

  createForm.appendChild(createParagraph);
  createForm.appendChild(optionsContainer);
  }

  const createSubmitButton = document.createElement('button');
  createSubmitButton.type = 'submit';
  createSubmitButton.textContent = 'Submit Quiz';

  createForm.appendChild(createSubmitButton)
  
  
}

